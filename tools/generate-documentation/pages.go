type link struct {
	Title string `json:"title"`
	URL   string `json:"url"`
}

func writePages(contentDir string, c *catalog) error {
	root := filepath.Join(contentDir, filepath.FromSlash(sectionID))
	if err := os.RemoveAll(root); err != nil {
		return err
	}

	var libraries []map[string]string
	for _, p := range c.libraries {
		libraries = append(libraries, map[string]string{
			"title":       p.Dir,
			"description": synopsis(p.Doc),
			"godoc":       godocURL + module + "/" + p.Dir,
			"source":      treeURL + p.Dir,
		})
	}
	err := writePage(root, "_index.md", map[string]any{
		"title":       "Components",
		"description": "Every service, middleware, and driver in reva, generated from the source code.",
		"weight":      30,
		"layout":      "components",
		"aliases":     []string{"/docs/autogenerated/", "/docs/autogenerated/packages/"},
		"params":      map[string]any{"generated": true, "libraries": libraries},
	}, "")
	if err != nil {
		return err
	}

	for kind, k := range kinds {
		err := writePage(filepath.Join(root, kind), "_index.md", map[string]any{
			"title":       k.Title,
			"description": k.Description,
			"weight":      k.Weight,
			"layout":      "component-list",
			"params":      map[string]any{"generated": true, "kind": kind},
		}, "")
		if err != nil {
			return err
		}
	}

	for _, f := range c.families {
		if len(f.Members) == 0 {
			continue
		}
		members := map[string]bool{}
		for _, m := range f.Members {
			members[m.pkg.Dir] = true
		}
		var desc, body string
		if p := c.pkgs[f.Registry]; p != nil {
			desc = synopsis(p.Doc)
			body = readmeMarkdown(p.Dir, p.Readme)
		}
		params := map[string]any{
			"generated":  true,
			"registry":   f.Registry,
			"category":   f.Category,
			"source":     treeURL + f.Registry,
			"namespaces": f.Namespaces,
			"used_by":    c.usedBy(f.Registry, members),
		}
		err := writePage(filepath.Join(root, "drivers", f.Slug), "_index.md", map[string]any{
			"title":       f.Title,
			"description": desc,
			"layout":      "family",
			"params":      params,
		}, body)
		if err != nil {
			return err
		}
	}

	for _, comp := range c.components {
		p := comp.pkg
		tables := []string{}
		if comp.Kind == kindDriver {
			for _, ns := range comp.Family.Namespaces {
				tables = append(tables, ns+"."+comp.Name)
			}
		} else if k := kinds[comp.Kind]; k.Table != "" {
			tables = append(tables, fmt.Sprintf(k.Table, comp.Name))
		}
		params := map[string]any{
			"generated":   true,
			"kind":        comp.Kind,
			"kind_title":  kinds[comp.Kind].Title,
			"category":    comp.Category,
			"name":        comp.Name,
			"builtin":     comp.Builtin,
			"dir":         p.Dir,
			"import_path": module + "/" + p.Dir,
			"source":      treeURL + p.Dir,
			"godoc":       godocURL + module + "/" + p.Dir,
			"tables":      tables,
			"config":      p.Config,
			"build_tags":  p.BuildTags,
		}
		if comp.Family != nil {
			params["family"] = comp.Family.Title
			params["family_url"] = comp.Family.URL
		}
		if comp.Kind == kindLibrary {
			params["used_by"] = c.usedBy(p.Dir, map[string]bool{p.Dir: true})
		}
		var others []string
		for _, r := range p.Regs[min(1, len(p.Regs)):] {
			others = append(others, kinds[r.Kind].Title+": "+r.Name)
		}
		params["also_registers"] = others

		var body string
		if p.Doc != "" {
			pr := comment.Printer{
				HeadingLevel: 2,
				DocLinkURL:   func(l *comment.DocLink) string { return godocURL + l.ImportPath },
			}
			body = string(pr.Markdown(new(comment.Parser).Parse(p.Doc)))
		}
		if p.Readme != "" {
			if body != "" {
				body += "\n"
			}
			body += readmeMarkdown(p.Dir, p.Readme)
		}

		// The previous generator published the configuration of a package here.
		oldURL := "/docs/autogenerated/packages/" + strings.TrimPrefix(p.Dir, "pkg/") + "/"
		if rest, ok := strings.CutPrefix(p.Dir, "internal/"); ok {
			oldURL = "/docs/autogenerated/" + rest + "/"
		}
		dir := filepath.Join(contentDir, filepath.FromSlash(strings.Trim(comp.URL, "/")))
		err := writePage(dir, "index.md", map[string]any{
			"title":       comp.Title,
			"description": synopsis(p.Doc),
			"layout":      "component",
			"aliases":     []string{oldURL},
			"params":      params,
		}, body)
		if err != nil {
			return err
		}
	}
	return nil
}

func writePage(dir, name string, front map[string]any, body string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	fm, err := json.MarshalIndent(front, "", "  ")
	if err != nil {
		return err
	}
	content := string(fm) + "\n\n" + strings.TrimSpace(body) + "\n"
	return os.WriteFile(path.Join(dir, name), []byte(content), 0o644)
}
