package cli

import "fmt"

// UsageError is a wrong use of a command that the command finds itself, for
// example an argument that the server catalog refuses. The CLI exits with 2
// for it, as for the errors that cobra finds before the command runs.
type UsageError struct{ Err error }

func (e *UsageError) Error() string { return e.Err.Error() }

func (e *UsageError) Unwrap() error { return e.Err }

// Usagef returns a UsageError.
func Usagef(format string, args ...any) error {
	return &UsageError{Err: fmt.Errorf(format, args...)}
}
